"""Generate <os>/syscall_nr.h from the upstream system call lists.

usage: gen-syscall-nr.py {freebsd|netbsd|openbsd|illumos|plan9} <upstream file>

Upstream files:
  freebsd  sys/kern/syscalls.master        (freebsd-src)
  netbsd   sys/kern/syscalls.master        (NetBSD src)
  openbsd  sys/kern/syscalls.master        (OpenBSD src)
  illumos  usr/src/uts/common/sys/syscall.h (illumos-gate)
  plan9    sys/src/libc/9syscall/sys.h     (9front)
"""
import re
import sys


def join_lines(text):
    return text.replace("\\\n", " ")


def freebsd(text):
    out = []
    # entries look like "<nr>\tAUE_x\tTYPE {\n\t\tint name(\n ... }"
    for m in re.finditer(r"^(\d+)\s+AUE_\w+\s+([\w|]+)\s*\{(.*?)^\t\}",
                         text, re.S | re.M):
        nr, kind, body = int(m.group(1)), m.group(2), m.group(3)
        fn = re.search(r"(\w+)\s*\(", body)
        if not fn or "OBSOL" in kind or "UNIMPL" in kind:
            continue
        name = fn.group(1)
        for c in re.findall(r"COMPAT\d*", kind):
            name = "freebsd" + c[6:] + "_" + name if c != "COMPAT" else "o" + name
        out.append((nr, name))
    return out


def netbsd(text):
    out = []
    for line in join_lines(text).splitlines():
        m = re.match(r"^(\d+)\s+(.*?)\{\s*[^|]*\|(\w*)\|(\w*)\|(\w+)\(", line)
        if not m:
            continue
        nr, kind, _, ver, name = m.groups()
        kind = kind.split()
        if kind[0] in ("OBSOL", "UNIMPL", "EXCL", "IGNORED"):
            continue
        if ver:
            name = "__%s%s" % (name, ver)
        if kind[0].startswith("COMPAT_"):
            name = "compat_%s_%s" % (kind[0][7:], name)
        out.append((int(nr), name))
    return out


def openbsd(text):
    out = []
    for line in join_lines(text).splitlines():
        m = re.match(r"^(\d+)\s+(\w+)[^{]*\{\s*.*?\bsys_(\w+)\(", line)
        if not m or m.group(2) in ("OBSOL", "UNIMPL"):
            continue
        out.append((int(m.group(1)), m.group(3)))
    return out


def illumos(text):
    out = []
    for m in re.finditer(r"^#define\s+SYS_(\w+)\s+(\d+)\s*$", text, re.M):
        out.append((int(m.group(2)), m.group(1)))
    return out


def plan9(text):
    out = []
    for m in re.finditer(r"^#define\s+(\w+)\s+(\d+)", text, re.M):
        out.append((int(m.group(2)), m.group(1).lower()))
    return out


def main():
    os_name, path = sys.argv[1], sys.argv[2]
    with open(path, encoding="utf-8", errors="replace") as f:
        calls = globals()[os_name](f.read())
    up = os_name.upper()
    print("/* SPDX-License-Identifier: GPL-2.0 */")
    print("/* Generated by scripts/gen-syscall-nr.py - do not edit. */")
    print("#ifndef _%s_SYSCALL_NR_H\n#define _%s_SYSCALL_NR_H\n" % (up, up))
    seen = set()
    for nr, name in sorted(calls):
        if name in seen:
            continue
        seen.add(name)
        print("#define %s_SYS_%s\t%d" % (up, name, nr))
    print("\n#define %s_SYS_MAXSYSCALL\t%d" % (up, max(n for n, _ in calls) + 1))
    print("\n#endif")


if __name__ == "__main__":
    main()
